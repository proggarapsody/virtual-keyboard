import { test, expect } from '@playwright/test'
test('per-key inheritance, decorative text, undo, and reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('status')).toHaveText('Saved')
  const a = page.locator('[data-code=KeyA]'), b = page.locator('[data-code=KeyB]')
  await a.click(); await page.getByLabel('Decorative legend', { exact: true }).fill('<sun>'); await page.getByLabel('Decorative legend', { exact: true }).press('Tab')
  await expect(a).toHaveText(/<sun>/)
  await page.getByLabel('Selected key color', { exact: true }).fill('#123456')
  await page.getByLabel('Key color', { exact: true }).fill('#abcdef')
  await expect(a).toHaveCSS('background-color', 'rgb(18, 52, 86)')
  await expect(b).toHaveCSS('background-color', 'rgb(171, 205, 239)')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(b).not.toHaveCSS('background-color', 'rgb(171, 205, 239)')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Saved')
  await page.reload(); await expect(a).toHaveText('<sun>')
  await a.click(); await page.getByRole('button', { name: 'Reset selected to global' }).click()
  await expect(a).toHaveCSS('background-color', 'rgb(171, 205, 239)')
})
test('fresh presets preserve previous work; library deletion is confirmed', async ({ page }) => {
  await page.goto('/'); await expect(page.getByRole('status')).toHaveText('Saved')
  await page.getByRole('button', { name: 'Quiet minimalist', exact: true }).click()
  await expect(page.locator('h1')).toHaveText('Quiet minimalist')
  await page.locator('.library .design-item').filter({ hasText: 'Tactile mechanical' }).click()
  await expect(page.locator('h1')).toHaveText('Tactile mechanical')
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Keep design' }).click(); await expect(page.locator('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await expect(page.locator('h1')).toHaveText('Tactile mechanical copy')
  await page.getByRole('button', { name: 'Undo', exact: true }).isDisabled()
})
