import { test, expect } from '@playwright/test'
import { resolve } from 'node:path'
const root = resolve('.')
test('uploads, trims, saves and exports self-contained media into a new context', async ({ page, browser }) => {
  await page.goto('/'); await expect(page.getByRole('status')).toHaveText('Saved')
  await page.getByText('Background image', { exact: true }).click()
  await page.getByLabel('Upload or replace image').setInputFiles(`${root}/e2e/fixtures/background.png`)
  await expect(page.getByRole('button', { name: 'Remove background', exact: true })).toBeVisible()
  await page.getByText('Sound assignments', { exact: true }).click()
  await page.getByLabel('Upload audio sample').setInputFiles(`${root}/public/sounds/tone.wav`)
  await expect(page.getByLabel('Trim end tone.wav', { exact: true })).toBeVisible()
  await page.getByLabel('Trim start tone.wav', { exact: true }).fill('0.01')
  await page.getByLabel('Trim start tone.wav', { exact: true }).press('Tab')
  await page.getByLabel('Trim end tone.wav', { exact: true }).fill('0.08')
  await page.getByLabel('Trim end tone.wav', { exact: true }).press('Tab')
  await expect(page.getByRole('status')).toHaveText('Saved')
  await page.reload(); await expect(page.locator('.canvas-background')).toHaveCSS('background-image', /blob:/)
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export design', exact: true }).first().click()
  const file = await download; const path = await file.path(); expect(path).toBeTruthy()
  const fresh = await browser.newContext(); const other = await fresh.newPage(); await other.goto('/')
  await expect(other.getByRole('status')).toHaveText('Saved')
  await other.getByLabel('Import design', { exact: true }).first().setInputFiles(path!)
  await expect(other.locator('.canvas-background')).toBeVisible()
  await expect(other.locator('.library .design-item')).toHaveCount(2)
  await other.getByText('Sound assignments', { exact: true }).click()
  await expect(other.getByLabel('Trim start tone.wav', { exact: true })).toHaveValue('0.01')
  await expect(other.getByLabel('Trim end tone.wav', { exact: true })).toHaveValue('0.08')
  await other.reload(); await expect(other.locator('.canvas-background')).toBeVisible()
  await fresh.close()
})
test('invalid image/audio/import keeps current work and exports remain available', async ({ page }) => {
  await page.goto('/'); await expect(page.getByRole('status')).toHaveText('Saved')
  await page.getByText('Sound assignments', { exact: true }).click()
  await page.getByLabel('Upload audio sample').setInputFiles({ name: 'bad.wav', mimeType: 'audio/wav', buffer: Buffer.from('no audio') })
  await expect(page.getByRole('alert')).toContainText('valid WAV')
  await page.getByLabel('Import design', { exact: true }).first().setInputFiles({ name: 'bad.keyboard-artist', mimeType: 'application/zip', buffer: Buffer.from('bad') })
  await expect(page.getByRole('alert')).toContainText('Existing designs are unchanged')
  await expect(page.locator('h1')).toHaveText('Tactile mechanical')
  await expect(page.locator('.library .design-item')).toHaveCount(1)
})
test('real Web Audio creates one press/release for repeats and concurrent sources', async ({ page }) => {
  await page.addInitScript(() => {
    const original = AudioBufferSourceNode.prototype.start
    const recorded: { count: number; rates: number[] } = { count: 0, rates: [] }
    Object.assign(window, { audioEvidence: recorded })
    AudioBufferSourceNode.prototype.start = function(...args: Parameters<typeof original>) { recorded.count++; recorded.rates.push(this.playbackRate.value); return original.apply(this, args) }
  })
  await page.goto('/'); await page.getByRole('button', { name: 'Enable sound', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sound enabled', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Play keyboard' }).click()
  await page.getByRole('textbox', { name: 'Scratchpad' }).focus()
  await page.keyboard.down('KeyA'); await page.keyboard.down('KeyA'); await page.keyboard.down('KeyB')
  await page.keyboard.up('KeyA'); await page.keyboard.up('KeyB')
  await expect.poll(() => page.evaluate(() => (window as unknown as { audioEvidence: { count: number } }).audioEvidence.count)).toBe(4)
  await page.getByRole('button', { name: 'Mute', exact: true }).click()
  await page.getByRole('textbox', { name: 'Scratchpad' }).focus(); await page.keyboard.press('KeyC')
  expect(await page.evaluate(() => (window as unknown as { audioEvidence: { count: number } }).audioEvidence.count)).toBe(4)
})
